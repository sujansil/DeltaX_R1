"""R1A request receipt capture and low-cardinality latency instrumentation."""
from __future__ import annotations

import logging
from time import perf_counter

from .timing import utc_now

logger = logging.getLogger("round1.r1a_latency")


class R1AReceiptTimingMiddleware:
    """Buffer only the tiny submit body and timestamp its final ASGI chunk.

    The timestamp is generated by the server and is never read from a header or
    request payload. Other routes pass through without body buffering.
    """
    def __init__(self, app):
        self.app = app

    async def __call__(self, scope, receive, send):
        path = scope.get("path")
        if (scope["type"] != "http" or scope.get("method") != "POST"
                or path not in ("/api/r1a/submit", "/api/r1b/submit")):
            await self.app(scope, receive, send)
            return
        messages = []
        while True:
            message = await receive()
            messages.append(message)
            if message["type"] == "http.disconnect" or not message.get("more_body", False):
                break
        prefix = "r1a" if path == "/api/r1a/submit" else "r1b"
        scope[f"{prefix}_received_at"] = utc_now()
        receipt_clock = perf_counter()
        scope[f"{prefix}_timing"] = {}

        async def replay():
            if messages:
                return messages.pop(0)
            return {"type": "http.request", "body": b"", "more_body": False}

        status = 500
        async def timed_send(message):
            nonlocal status
            if message["type"] == "http.response.start":
                status = message["status"]
                timing = scope[f"{prefix}_timing"]
                total = (perf_counter() - receipt_clock) * 1000
                values = {key: round(value, 3) for key, value in timing.items()}
                values["receipt_to_response_ms"] = round(total, 3)
                headers = list(message.get("headers", []))
                server_timing = ", ".join(
                    f'{name.replace("_ms", "")};dur={value}' for name, value in values.items())
                headers.append((b"server-timing", server_timing.encode("ascii")))
                message = {**message, "headers": headers}
                logger.info("%s_submit_latency status=%s %s", prefix, status,
                            " ".join(f"{key}={value}" for key, value in values.items()))
            await send(message)

        await self.app(scope, replay, timed_send)
